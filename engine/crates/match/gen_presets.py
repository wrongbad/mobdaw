"""Generate client/src/content/presets.matched.ts from match_chain best.json files.
usage: python3 -I gen_presets.py <out.ts> <calibration rev> <run dir>...
A program found in several run dirs takes the last one given."""
import json, os, sys
out, rev, runs = sys.argv[1], sys.argv[2], sys.argv[3:]
names = {"clarinet": "Clarinet", "alto-sax": "Alto sax", "flute": "Flute", "cello": "Cello", "violin": "Violin"}
cat = {"clarinet": "winds", "alto-sax": "winds", "flute": "winds", "cello": "strings", "violin": "strings"}
src = {}
for r in runs:
    for k in names:
        if os.path.exists(f"{r}/{k}/best.json"):
            src[k] = r
def lit(d): return "{ " + ", ".join(f"{i}: {round(v, 4)}" for i, v in d.items()) + " }"
def bands(bs):
    d = {}
    for i, e in enumerate(bs):
        d.update({i * 3: e["freq_hz"], i * 3 + 1: e["gain_db"], i * 3 + 2: e["damping"]})
    d[len(bs) * 3] = 0
    return d
rows = []
for k in names:
    if k not in src:
        continue
    j = json.load(open(f"{src[k]}/{k}/best.json"))
    b = j["bore"]
    bore = {0: b["character"], 1: b["stiffness"], 2: b["aperture"], 3: b["position"], 4: b["bore"], 5: b["damping"], 6: b["decay"],
            7: b["breath"], 8: b["noise"], 9: b["vibrato_hz"], 10: b["vibrato_depth"], 11: b["attack_ms"], 12: b["release_ms"], 13: 1,
            14: b.get("pitch_vibrato", 0)}
    f, r = j["filter"], j["reverb"]
    fx = ([("BODY", bands(j["body"]))] if "body" in j else []) + [
        ("SIMPLE_FILTER", {0: 0, 1: f["cutoff_hz"], 2: f["damping"], 3: 0}), ("EQ", bands(j["eq"])),
        ("REVERB", {0: r["mix"], 1: r["size"], 2: r["damping"], 3: r["predelay_ms"]})]
    fxs = ",\n      ".join(f"{{ type: {t}, params: {lit(p)} }}" for t, p in fx)
    rows.append(f"""  {{
    id: 'gm-{k}', name: 'GM {names[k]}', category: '{cat[k]}', gm: {j['gm']}, loss: {j['wet_loss']}, run: '{os.path.basename(os.path.normpath(src[k]))}', type: BORE,
    params: {lit(bore)},
    fx: [
      {fxs},
    ],
  }}""")
labels = sorted({os.path.basename(os.path.normpath(v)) for v in src.values()})
types = sorted({"BORE", "EQ", "REVERB", "SIMPLE_FILTER"} | ({"BODY"} if any("BODY" in r for r in rows) else set()))
open(out, "w").write(f"""// GENERATED by engine/crates/match/gen_presets.py from docs/match/runs/{{{','.join(labels)}}} -- do not edit; re-run the match instead.
// Each preset is a bore voice plus the (body ->) filter -> EQ -> reverb chain fitted jointly against a General MIDI soundfont
// program (docs/matching.md). Hand-tuned presets live in presets.ts and are never touched by the tooling.
import {{ {', '.join(types)} }} from '@mobdaw/shared'

/** The bore_cal.rs revision these were fitted against; a refit changes how they sound. */
export const MATCHED_CALIBRATION = '{rev}'

export type MatchedPreset = {{
  id: string; name: string; category: 'winds' | 'strings'; gm: number; loss: number; run: string; type: number
  params: Record<string, number>
  fx: {{ type: number; params: Record<string, number> }}[]
}}

export const MATCHED_PRESETS: MatchedPreset[] = [
{(","+chr(10)).join(rows)},
]
""")
