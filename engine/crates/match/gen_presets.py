"""Generate client/src/content/presets.matched.ts from match_chain best.json files.
usage: python3 -I gen_presets.py <run dir> <out.ts> <calibration rev> <run label>"""
import json, sys
run, out, rev, label = sys.argv[1:5]
names = {"clarinet": "Clarinet", "alto-sax": "Alto sax", "flute": "Flute", "cello": "Cello", "violin": "Violin"}
cat = {"clarinet": "winds", "alto-sax": "winds", "flute": "winds", "cello": "strings", "violin": "strings"}
rows = []
for k in names:
    j = json.load(open(f"{run}/{k}/best.json"))
    b = j["bore"]
    bore = {0: b["character"], 1: b["stiffness"], 2: b["aperture"], 3: b["position"], 4: b["bore"], 5: b["damping"], 6: b["decay"],
            7: b["breath"], 8: b["noise"], 9: b["vibrato_hz"], 10: b["vibrato_depth"], 11: b["attack_ms"], 12: b["release_ms"], 13: 1}
    f = j["filter"]
    eq = {12: 0}
    for i, e in enumerate(j["eq"]):
        eq.update({i * 3: e["freq_hz"], i * 3 + 1: e["gain_db"], i * 3 + 2: e["damping"]})
    r = j["reverb"]
    fx = [("SIMPLE_FILTER", {0: 0, 1: f["cutoff_hz"], 2: f["damping"], 3: 0}), ("EQ", eq),
          ("REVERB", {0: r["mix"], 1: r["size"], 2: r["damping"], 3: r["predelay_ms"]})]
    def lit(d): return "{ " + ", ".join(f"{i}: {round(v, 4)}" for i, v in d.items()) + " }"
    fxs = ",\n      ".join(f"{{ type: {t}, params: {lit(p)} }}" for t, p in fx)
    rows.append(f"""  {{
    id: 'gm-{k}', name: 'GM {names[k]}', category: '{cat[k]}', gm: {j['gm']}, loss: {j['wet_loss']}, type: BORE,
    params: {lit(bore)},
    fx: [
      {fxs},
    ],
  }}""")
open(out, "w").write(f"""// GENERATED by engine/crates/match/gen_presets.py from docs/match/runs/{label} -- do not edit; re-run the match instead.
// Each preset is a bore voice plus the filter -> EQ -> reverb chain fitted jointly against a General MIDI soundfont program
// (docs/matching.md). Hand-tuned presets live in presets.ts and are never touched by the tooling.
import {{ BORE, EQ, REVERB, SIMPLE_FILTER }} from '@mobdaw/shared'

/** `calibration`: the bore_cal.rs revision these were fitted against; a refit changes how they sound. */
export const MATCHED_CALIBRATION = '{rev}'

export type MatchedPreset = {{
  id: string; name: string; category: 'winds' | 'strings'; gm: number; loss: number; type: number
  params: Record<string, number>
  fx: {{ type: number; params: Record<string, number> }}[]
}}

export const MATCHED_PRESETS: MatchedPreset[] = [
{(","+chr(10)).join(rows)},
]
""")
